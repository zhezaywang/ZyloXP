import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { chromium } from '@playwright/test';
import { labValues } from '../tests/fixtures/labValues.mjs';

const server = await createServer({ cacheDir: 'node_modules/.cache/zyloxp-reference-renderer', server: { middlewareMode: true, hmr: false, ws: false }, optimizeDeps: { noDiscovery: true, include: [] }, appType: 'custom' });
let browser;
try {
  const { LabSchematic } = await server.ssrLoadModule('/src/LabVisualStage.tsx');
  const { labScenarios } = await server.ssrLoadModule('/src/data.ts');
  const css = await readFile('src/styles.css', 'utf8');
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
  const generated = [];
  for (const lab of labScenarios.filter((item) => /^\/lab-[a-z-]+-reference\.svg$/.test(item.diagram))) {
    const markup = renderToStaticMarkup(createElement(LabSchematic, { lab, values: labValues, running: false }));
    await page.setContent(`<!doctype html><meta charset="utf-8"><style>${css}*{animation:none!important;transition:none!important}</style>${markup}`);
    const svg = await page.locator('.labSchematic svg').evaluate((source, title) => {
      const clone = source.cloneNode(true);
      const properties = ['fill', 'fill-opacity', 'stroke', 'stroke-width', 'stroke-opacity', 'stroke-dasharray', 'stroke-dashoffset',
        'stroke-linecap', 'stroke-linejoin', 'opacity', 'filter', 'font-family', 'font-size', 'font-weight', 'font-style',
        'letter-spacing', 'text-anchor', 'dominant-baseline', 'paint-order', 'visibility', 'transform', 'transform-origin', 'transform-box'];
      const elements = [source, ...source.querySelectorAll('*')];
      const copies = [clone, ...clone.querySelectorAll('*')];
      elements.forEach((element, index) => {
        const computed = getComputedStyle(element);
        for (const property of properties) {
          const value = computed.getPropertyValue(property).replace(/url\(["']?([^"')]+)["']?\)/g, (match, url) => {
            const hash = new URL(url, document.baseURI).hash;
            return hash ? `url(${hash})` : match;
          });
          copies[index].style.setProperty(property, value);
        }
        copies[index].removeAttribute('class');
      });
      clone.querySelectorAll('style').forEach((element) => element.remove());
      clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
      clone.setAttribute('width', '1280');
      clone.setAttribute('height', '720');
      clone.setAttribute('role', 'img');
      clone.removeAttribute('aria-label');
      clone.setAttribute('aria-labelledby', 'reference-title');
      const titleElement = document.createElementNS('http://www.w3.org/2000/svg', 'title');
      titleElement.id = 'reference-title';
      titleElement.textContent = `${title}: fixed example from the live teaching model`;
      clone.prepend(titleElement);
      return new XMLSerializer().serializeToString(clone);
    }, lab.title);
    const file = path.join('public', lab.diagram);
    await writeFile(file, `<!-- Generated by tools/render-lab-references.mjs; edit the live renderer instead. -->\n${svg}\n`);
    generated.push(file);
  }
  console.log(JSON.stringify({ generated }));
} finally {
  await browser?.close();
  await server.close();
}
